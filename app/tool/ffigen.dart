// Generator-only tooling, intentionally not an application dependency.
// Use an isolated package with ffigen 21.0.0 and libclang 18.1.1:
// dart --packages=<tool-root>/.dart_tool/package_config.json tool/ffigen.dart <libclang.dll>
import 'dart:io';

import 'package:ffigen/ffigen.dart';

void main(List<String> args) {
  final app = Platform.script.resolve('../');
  FfiGenerator(
    headers: Headers(
      entryPoints: [app.resolve('third_party/sqlite_interrupt.h')],
    ),
    functions: Functions(
      include: (declaration) => declaration.originalName == 'sqlite3_interrupt',
      recordUse: (_) => true,
    ),
    output: Output(
      dartFile: app.resolve('lib/src/third_party/sqlite_interrupt.g.dart'),
      recordUseMapping: app.resolve(
        'lib/src/third_party/sqlite_interrupt.record_use_mapping.g.dart',
      ),
      style: const NativeExternalBindings(
        assetId: 'package:sqlite3/src/ffi/libsqlite3.g.dart',
      ),
      preamble:
          '''// SQLite public-domain C API. SQLite authors disclaim copyright.
// Generated by package:ffigen. Do not edit manually.
// ignore_for_file: type=lint, experimental_member_use
''',
    ),
  ).generate(libclangDylib: File(args.single).absolute.uri);
}
